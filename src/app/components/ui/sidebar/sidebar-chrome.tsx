"use client";

import * as React from "react";
import { SidebarSimple as PanelLeftIcon } from "@phosphor-icons/react";

import { SIDEBAR_TRIGGER_BUTTON_CLASS } from "../../../config/sidebar-ui";
import { Button } from "../button";
import { Input } from "../input";
import { Separator } from "../separator";
import { cn } from "../utils";

import { SIDEBAR_COPY_EN } from "./sidebar-copy.en";
import { useSidebar } from "./sidebar-context";

function SidebarTrigger({
  className,
  onClick,
  ...props
}: React.ComponentProps<typeof Button>) {
  const { toggleSidebar } = useSidebar();

  return (
    <Button
      data-sidebar="trigger"
      data-slot="sidebar-trigger"
      variant="ghost"
      size="icon"
      className={cn(SIDEBAR_TRIGGER_BUTTON_CLASS, className)}
      onClick={(event) => {
        onClick?.(event);
        toggleSidebar();
      }}
      {...props}
    >
      <PanelLeftIcon />
      <span className="sr-only">{SIDEBAR_COPY_EN.toggleSidebar}</span>
    </Button>
  );
}

function SidebarRail({ className, ...props }: React.ComponentProps<"button">) {
  const { toggleSidebar } = useSidebar();

  return (
    <button
      data-sidebar="rail"
      data-slot="sidebar-rail"
      aria-label={SIDEBAR_COPY_EN.toggleSidebar}
      tabIndex={-1}
      onClick={toggleSidebar}
      title={SIDEBAR_COPY_EN.toggleSidebar}
      className={cn(
        "hover:after:bg-sidebar-border absolute inset-y-0 z-20 hidden w-4 -translate-x-1/2 transition-all ease-linear group-data-[side=left]:-right-4 group-data-[side=right]:left-0 after:absolute after:inset-y-0 after:left-1/2 after:w-[length:var(--space-0-5)] sm:flex",
        "in-data-[side=left]:cursor-w-resize in-data-[side=right]:cursor-e-resize",
        "[[data-side=left][data-state=collapsed]_&]:cursor-e-resize [[data-side=right][data-state=collapsed]_&]:cursor-w-resize",
        "hover:group-data-[collapsible=offcanvas]:bg-sidebar group-data-[collapsible=offcanvas]:translate-x-0 group-data-[collapsible=offcanvas]:after:left-full",
        "[[data-side=left][data-collapsible=offcanvas]_&]:-right-2",
        "[[data-side=right][data-collapsible=offcanvas]_&]:-left-2",
        className,
      )}
      {...props}
    />
  );
}

