/**
 * EvaluationDataset — Per-phase run records for observability and future learning.
 *
 * These rows are inserted after each phase completes, with PII sanitized.
 * Default retention: 90 days. Extended retention: 1 year (internal/learning samples).
 *
 * Phase 2+: advisory logging only. Phase 5+: feeds agent performance aggregation.
 *
 * Corresponds to the `evaluation_datasets` Supabase table.
 * See docs/adrs/ADR-TRUTH-REGISTRY-ASSUMPTIONS.md §Evaluation Dataset.
 */

import type { ControlObjectV1 } from '../schemas/control-object.js';
import type { DomainKey } from './audit.js';
import { EVALUATION_DATASET_RETENTION_TTL_DAYS } from '../config/evaluation-dataset-retention.js';

// ─── Retention ────────────────────────────────────────────────────────────────

export type RetentionPolicy = 'default' | 'extended' | 'internal_only';

/** TTL in days per retention policy (mirrors the DB CASE expression). */
export const RETENTION_TTL_DAYS = EVALUATION_DATASET_RETENTION_TTL_DAYS;

// ─── Human Feedback ───────────────────────────────────────────────────────────

/**
 * Optional consultant-provided feedback on the phase output.
 * Recorded post-phase during review gates or manual inspection.
 */
export interface HumanFeedback {
  /** Consultant's final decision on this run */
  decision: 'accept' | 'refine' | 'restart';
  /** Free-text corrections noted by the consultant */
  corrections?: string;
  /** Any additional context notes */
  notes?: string;
  /** ISO timestamp when feedback was recorded */
  recorded_at?: string;
}

// ─── Row Shape ────────────────────────────────────────────────────────────────

/**
 * Full row shape for `evaluation_datasets` table.
 * All `JSONB` columns are typed explicitly; `id` and timestamps are DB-generated.
 */
export interface EvaluationDatasetRow {
  /** UUID — generated by DB */
  id: string;
  audit_id: string;
  phase_id: DomainKey | 'recon' | 'strategy';
  /** Monotonically increasing per (audit_id, phase_id) — 1 for first run, 2 after rerun, etc. */
  run_number: number;

  /** Full CONTROL_OBJECT v1.5 snapshot as emitted at end of phase */
  control_object: ControlObjectV1;
  /** Raw agent output (DomainResult JSON) BEFORE fact-checker corrections */
  agent_output: Record<string, unknown>;
  /** Agent output AFTER fact-checker corrections (what was saved to audit_domains) */
  cleaned_output: Record<string, unknown>;

  /** Optional consultant feedback (null until review gate is processed) */
  human_feedback: HumanFeedback | null;

  /** Which decision was applied in the pipeline for this run */
  decision_applied: 'accept' | 'accept_with_warnings' | 'refine' | null;

  /**
   * Retention policy governs how long this row is kept.
   * Async expiry job deletes rows past `expires_at`.
   */
  retention_policy: RetentionPolicy;

  /**
   * True if PII fields (domain name, client identifiers, contact info) have been
   * masked/sanitised before insert. Must be true before any row is inserted in prod.
   */
  pii_sanitized: boolean;

  /** DB-generated insert timestamp */
  created_at: string;

  /**
   * DB-generated expiry timestamp.
   * Computed as: created_at + (retention_ttl_days × INTERVAL '1 day')
   * Managed by the DB GENERATED ALWAYS expression — do not set manually.
   */
  expires_at: string;
}

// ─── Insert Payload ───────────────────────────────────────────────────────────

/**
 * Payload shape for inserting a new evaluation dataset row.
 * Excludes DB-generated fields (id, created_at, expires_at).
 */
export type EvaluationDatasetInsert = Omit<EvaluationDatasetRow, 'id' | 'created_at' | 'expires_at'>;

