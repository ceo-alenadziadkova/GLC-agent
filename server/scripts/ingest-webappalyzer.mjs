/**
 * Fetches technology fingerprints from enthec/webappanalyzer and emits
 * server/src/lib/wappalyzer-imported-rules.ts (raw patterns, compiled at runtime).
 *
 * Run: node scripts/ingest-webappalyzer.mjs
 * Requires network once; commit the generated TS file to avoid CI network dependency.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '../src/lib/wappalyzer-imported-rules.ts');
const BASE = 'https://raw.githubusercontent.com/enthec/webappanalyzer/main/src/technologies';

/** First Wappalyzer category id -> GLC TechCategory */
const CAT_MAP = {
  1: 'cms',
  6: 'ecommerce',
  10: 'analytics',
  12: 'frameworks',
  18: 'frameworks',
  31: 'hosting_cdn',
  32: 'email_marketing',
  36: 'analytics',
  41: 'ecommerce',
  42: 'analytics',
  51: 'cms',
  52: 'chat_support',
  53: 'chat_support',
  54: 'analytics',
  57: 'frameworks',
  62: 'hosting_cdn',
  66: 'frameworks',
  67: 'analytics',
  72: 'booking',
  75: 'email_marketing',
  78: 'analytics',
  88: 'hosting_cdn',
};

/** Names we hand-maintain in WAPPALYZER_CORE_RULES — skip to avoid duplicate work. */
const SKIP_NAMES = new Set(
  [
    'Magento',
    'Angular',
    'React',
    'Cloudflare',
    'Netlify',
    'GitHub Pages',
    'Vercel',
  ].map(s => s.toLowerCase()),
);

const LETTERS = 'abcdefghijklmnopqrstuvwxyz'.split('').concat('_');

function stripWappTags(s) {
  return String(s).split(/\\;/)[0] ?? '';
}

const MIN_PATTERN_LEN = 10;
const MAX_RULES = 900;

function okPattern(s) {
  const core = stripWappTags(s);
  if (core.length < MIN_PATTERN_LEN) return false;
  if (core.length > 240) return false;
  return true;
}

function normalizeStrArray(val) {
  if (!val) return [];
  if (typeof val === 'string') return okPattern(val) ? [stripWappTags(val)] : [];
  if (Array.isArray(val)) return val.filter(okPattern).map(stripWappTags);
  return [];
}

function normalizeMeta(meta) {
  if (!meta || typeof meta !== 'object' || Array.isArray(meta)) return [];
  const out = [];
  for (const [key, val] of Object.entries(meta)) {
    if (typeof val !== 'string' || !okPattern(val)) continue;
    const kind = key.includes(':') ? 'property' : 'name';
    out.push({ kind, key, pattern: stripWappTags(val) });
  }
  return out;
}

async function fetchJson(name) {
  const url = `${BASE}/${name}.json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`fetch ${url} ${res.status}`);
  return res.json();
}

async function main() {
  const merged = {};
  for (const L of LETTERS) {
    const chunk = await fetchJson(L);
    Object.assign(merged, chunk);
  }

  const rawRules = [];
  const seen = new Set();

  for (const [name, tech] of Object.entries(merged)) {
    if (!name || typeof name !== 'string' || name.length < 2) continue;
    if (SKIP_NAMES.has(name.toLowerCase())) continue;
    const cats = tech.cats;
    if (!Array.isArray(cats) || cats.length === 0) continue;
    const glcCat = CAT_MAP[cats[0]];
    if (!glcCat) continue;

    const html = normalizeStrArray(tech.html);
    const scriptSrc = normalizeStrArray(tech.scriptSrc);
    const scripts = normalizeStrArray(tech.scripts);
    const url = normalizeStrArray(tech.url);
    const meta = normalizeMeta(tech.meta);

    const hasSignal =
      html.length + scriptSrc.length + scripts.length + url.length + meta.length > 0;
    if (!hasSignal) continue;

    const key = `${glcCat}::${name.toLowerCase()}`;
    if (seen.has(key)) continue;
    seen.add(key);

    rawRules.push({
      category: glcCat,
      name,
      ...(html.length ? { html } : {}),
      ...(scriptSrc.length ? { scriptSrc } : {}),
      ...(scripts.length ? { scripts } : {}),
      ...(url.length ? { url } : {}),
      ...(meta.length ? { meta } : {}),
    });
  }

  function scoreRule(r) {
    const lens = (arr) => (arr ? arr.reduce((s, x) => s + (typeof x === 'string' ? x.length : 0), 0) : 0);
    return (
      lens(r.html) * 2 +
      lens(r.scriptSrc) * 3 +
      lens(r.scripts) * 2 +
      lens(r.url) * 2 +
      (r.meta ? r.meta.reduce((s, m) => s + m.pattern.length + m.key.length, 0) : 0)
    );
  }

  rawRules.sort((a, b) => scoreRule(b) - scoreRule(a) || a.name.localeCompare(b.name));
  const capped = rawRules.slice(0, MAX_RULES);
  capped.sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));

  const header = `/**\n * AUTO-GENERATED by scripts/ingest-webappalyzer.mjs from enthec/webappanalyzer.\n * Do not edit by hand. Re-run the script to refresh.\n *\n * Patterns are Wappalyzer-style regex sources (case-insensitive); \\;tags stripped at ingest.\n */\n\n`;
  const candidateCount = rawRules.length;
  const body = `export type WappalyzerImportedRuleRaw = {\n  category:\n    | 'cms'\n    | 'analytics'\n    | 'frameworks'\n    | 'hosting_cdn'\n    | 'chat_support'\n    | 'ecommerce'\n    | 'email_marketing'\n    | 'booking';\n  name: string;\n  html?: string[];\n  scriptSrc?: string[];\n  scripts?: string[];\n  url?: string[];\n  meta?: Array<{ kind: 'name' | 'property'; key: string; pattern: string }>;\n};\n\nexport const WAPPALYZER_IMPORTED_RULES_RAW: readonly WappalyzerImportedRuleRaw[] = ${JSON.stringify(capped, null, 2)} as const;\n`;

  fs.writeFileSync(OUT, header + body, 'utf8');
  console.log('Wrote', OUT, 'rules:', capped.length, '(from', candidateCount, 'candidates)');
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
